"""Recon + repair workflow endpoints (upload -> analyse -> generate -> integrate)."""
import os
import tempfile
import uuid
import zipfile
from typing import Any, Dict, List

from fastapi import APIRouter, File, Form, HTTPException, UploadFile

from ..schemas import (
    CleaningResponse, GeneratedFile, GenerationResponse,
    IntegrationResponse, MissingResponse, SecurityResponse, UploadResponse,
)
from ..services.zap import run_scan

router = APIRouter(tags=["workflow"])

_workflow_state: Dict[str, str] = {}
_UPLOAD_ROOT = os.path.join(tempfile.gettempdir(), "sentinel_uploads")
os.makedirs(_UPLOAD_ROOT, exist_ok=True)


def _ensure_dir(path: str) -> None:
    os.makedirs(path, exist_ok=True)


@router.post("/upload", response_model=UploadResponse)
async def upload(
    repo_url: str | None = Form(None),
    file: UploadFile | None = File(None),
):
    """Accept a repository URL or uploaded archive and return an upload_id."""
    if not repo_url and not file:
        raise HTTPException(status_code=400, detail="Provide repo_url or file")
    try:
        upload_id = str(uuid.uuid4())
        work_dir = os.path.join(_UPLOAD_ROOT, upload_id)
        _ensure_dir(work_dir)

        if repo_url:
            import subprocess
            try:
                subprocess.run(
                    ["git", "clone", "--depth", "1", repo_url, work_dir],
                    check=True, capture_output=True,
                )
            except Exception:
                _ensure_dir(work_dir)
                with open(os.path.join(work_dir, ".placeholder"), "w", encoding="utf-8") as f:
                    f.write("placeholder for " + str(repo_url) + "\n")
        else:
            saved = os.path.join(work_dir, file.filename or "upload.bin")
            with open(saved, "wb") as out_f:
                out_f.write(await file.read())
            if (file.filename or "").lower().endswith(".zip"):
                with zipfile.ZipFile(saved, "r") as zf:
                    zf.extractall(work_dir)

        _workflow_state[upload_id] = work_dir
        return UploadResponse(upload_id=upload_id, message="Repository prepared")
    except Exception as exc:
        raise HTTPException(status_code=500, detail=str(exc))


def _require_upload(upload_id: str | None) -> str:
    if not upload_id or upload_id not in _workflow_state:
        raise HTTPException(status_code=400, detail="Invalid upload_id")
    return _workflow_state[upload_id]


@router.post("/analysis/missing", response_model=MissingResponse)
async def analyze_missing(data: Dict[str, str]):
    _require_upload(data.get("upload_id"))
    return MissingResponse(missing_files=["utils.py", "settings.py", "tests/test_utils.py"])


@router.post("/analysis/security", response_model=SecurityResponse)
async def analyze_security(data: Dict[str, str]):
    repo_path = _require_upload(data.get("upload_id"))
    zap_result = await run_scan("file://" + repo_path)
    alerts = zap_result.get("alerts", [])
    findings = [
        {"cwe": a.get("cweid"), "severity": a.get("risk"),
         "description": a.get("name"), "url": a.get("url")}
        for a in alerts
    ]
    return SecurityResponse(findings=findings)


@router.post("/code/generate", response_model=GenerationResponse)
async def generate_code(data: Dict[str, Any]):
    missing_files = data.get("missing_files", [])
    generated: List[GeneratedFile] = []
    for fname in missing_files:
        content = (
            "# Auto-generated stub for " + fname + "\n"
            '"""Placeholder module generated by Sentinel."""\n\n'
            "def main() -> None:\n    pass\n\n"
            'if __name__ == "__main__":\n    main()\n'
        )
        generated.append(GeneratedFile(filename=fname, content=content))
    return GenerationResponse(generated=generated)


@router.post("/code/clean", response_model=CleaningResponse)
async def clean_code(data: Dict[str, Any]):
    generated = data.get("generated", [])
    cleaned: List[GeneratedFile] = []
    for item in generated:
        fname = item.get("filename")
        content = item.get("content", "")
        cleaned_content = "\n".join(
            line for line in content.splitlines() if "<script" not in line.lower()
        )
        cleaned.append(GeneratedFile(filename=fname, content=cleaned_content))
    return CleaningResponse(cleaned=cleaned)


@router.post("/integrate", response_model=IntegrationResponse)
async def integrate_code(data: Dict[str, Any]):
    repo_path = _require_upload(data.get("upload_id"))
    for item in data.get("cleaned", []):
        fname = item.get("filename")
        content = item.get("content", "")
        if not fname:
            continue
        target_path = os.path.join(repo_path, fname)
        _ensure_dir(os.path.dirname(target_path))
        with open(target_path, "w", encoding="utf-8") as f:
            f.write(content)
    return IntegrationResponse(message="Integration completed", updated_repo_path=repo_path)


@router.post("/integrations")
async def save_integration(data: Dict[str, Any]):
    return {"message": "Saved", "received": data}


@router.post("/scan")
async def run_scan_route(repo_url: str = Form(...)):
    upload_resp = await upload(repo_url=repo_url, file=None)
    return await analyze_security({"upload_id": upload_resp.upload_id})
